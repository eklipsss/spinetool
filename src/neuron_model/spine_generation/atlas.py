def traversal(vae: VAEHandle, base: Sequence[Tuple[str, np.ndarray]], real_latents: np.ndarray, *, n_directions: int, steps: Sequence[float],
              resolution: int, progress: bool = True) -> Dict[str, Any]:
    """Meshes of mu + t * sigma_d * e_d for the first principal directions of the REAL latents (e_d unit, sigma_d their
    std) and every base spine; with morphometrics and surface quality of every frame."""
    from sklearn.decomposition import PCA

    from ..spine_morphometrics import compute_scalar_metrics
    from .data.bbox import FrozenBBox
    from .evaluation.attachment import DownFacingCapFinder
    from .experiment.config import load_config, resolve_path
    from .models.spine_vae.generate import latent_to_mesh

    pca = PCA(n_components=min(n_directions, real_latents.shape[1], max(1, len(real_latents) - 1))).fit(real_latents)
    sig = np.sqrt(pca.explained_variance_)
    bbox = FrozenBBox.load(resolve_path(vae.cfg["data"]["bbox"]))
    mc = load_config(resolve_path(vae.cfg["reconstruction"]["marching_cubes_config"]))
    finder = DownFacingCapFinder()
    jobs = [(s, d, t) for s in range(len(base)) for d in range(len(sig)) for t in steps]
    it = jobs
    if progress:
        from tqdm.auto import tqdm

        it = tqdm(jobs, desc="latent traversal")
    frames: Dict[Tuple[int, int, float], Dict[str, Any]] = {}
    for s, d, t in it:
        z = base[s][1] + t * sig[d] * pca.components_[d]
        res = latent_to_mesh(vae.model, z, bbox=(bbox.low, bbox.high), resolution=resolution, coord_scale=vae.coord_scale, device=vae.device,
                             chunk_size=int(mc.get("chunk_size", 262_144)), iso_level=float(mc.get("iso_level", 0.0)),
                             postprocess_cfg=mc.get("postprocess"), check_self_intersections=False)
        mesh = res["mesh_postprocessed"] if res["mesh_postprocessed"] is not None else res["mesh_raw"]
        metrics: Dict[str, Optional[float]] = {}
        if mesh is not None and len(mesh.faces):
            try:
                metrics = {m: _float(v) for m, v in compute_scalar_metrics(mesh, finder(mesh)).items()}
            except Exception:
                metrics = {}
        frames[(s, d, t)] = {"mesh": mesh, "metrics": metrics, "quality": mesh_quality(mesh), "valid": bool(res["validation_raw"].get("is_valid", False))}
    return {"directions": [{"index": d, "sigma": float(sig[d]), "explained": float(pca.explained_variance_ratio_[d])} for d in range(len(sig))],
            "steps": [float(t) for t in steps], "base": [k for k, _ in base], "frames": frames}
