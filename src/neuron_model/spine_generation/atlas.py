@dataclass
class SpineRecord:
    source: str
    key: str
    latent: Optional[np.ndarray] = None
    metrics: Dict[str, Optional[float]] = field(default_factory=dict)
    quality: Dict[str, Any] = field(default_factory=dict)
    meta: Dict[str, Any] = field(default_factory=dict)
    mesh: Any = None  # trimesh kept only for the spines shown in the viewer


def _float(v: Any) -> Optional[float]:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return f if math.isfinite(f) else None


def real_records(vae: VAEHandle, index: Any, n: int, *, seed: int, n_meshes: int, source: str = "real", progress: bool = True) -> List[SpineRecord]:
    """``n`` random spines of ``index``: latent, stage-8 morphometrics, metadata; meshes (+ quality) for ``n_meshes``."""
    from ..pointcloud_io import load_pointcloud
    from ..spine_geometry import load_trimesh

    frame = index.frame
    rng = np.random.default_rng(seed)
    order = rng.permutation(len(frame))[: n]
    rows = frame.iloc[order].to_dict("records")
    it = rows
    if progress:
        from tqdm.auto import tqdm

        it = tqdm(rows, desc=f"{source}: encode")
    out = []
    for k, row in enumerate(it):
        rec = SpineRecord(source=source, key=str(row["spine_key"]))
        rec.meta = {c: (None if pd.isna(row.get(c)) else str(row.get(c))) for c in ("neuron_id", "cell_type", "cell_type_binary", "compartment", "split")}
        try:
            pc = load_pointcloud(row[f"pointcloud_{vae.n_points}_path"], vae.n_points, 1)
            rec.latent = encode(vae, pc["points"], pc.get("normals"))
        except Exception as exc:  # unreadable cloud: the spine stays out of the latent map
            rec.meta["error"] = repr(exc)[:200]
        path = row.get("morphometrics_path")
        if path and Path(path).exists():
            data = json.loads(Path(path).read_text(encoding="utf-8"))
            rec.metrics = {m: _float(data.get(m)) for m in SCALAR_METRICS}
        if k < n_meshes and row.get("local_sealed_mesh_path") and Path(row["local_sealed_mesh_path"]).exists():
            rec.mesh = load_trimesh(Path(row["local_sealed_mesh_path"]), process=False)
            rec.quality = mesh_quality(rec.mesh)
        out.append(rec)
    return out


def generated_records(vae: VAEHandle, seed_dir: Path, source: str, *, n: int, n_meshes: int, mesh_kind: str = "postprocessed",
                      seed: int = 0, progress: bool = True) -> List[SpineRecord]:
    """Samples of one generated set: latent of the mesh surface, morphometrics (attachment found geometrically, as in the
    evaluation), validity report of the generator, surface quality."""
    from ..spine_morphometrics import compute_scalar_metrics
    from .evaluation.attachment import DownFacingCapFinder
    from .evaluation.inputs import load_generated_set

    meshes, reports, ids = load_generated_set(Path(seed_dir), mesh_kind)
    meshes, reports, ids = meshes[:n], reports[:n], ids[:n]
    finder = DownFacingCapFinder()
    it = list(zip(meshes, reports, ids))
    if progress:
        from tqdm.auto import tqdm

        it = tqdm(it, desc=f"{source}: encode + morphometrics")
    out = []
    for k, (mesh, report, sid) in enumerate(it):
        rec = SpineRecord(source=source, key=f"{source}/{sid}")
        rec.meta = {"valid": bool(report.get("is_valid", False))}
        if mesh is not None and len(mesh.faces):
            try:
                pts, nrm = surface_cloud(mesh, vae.n_points, seed + k)
                rec.latent = encode(vae, pts, nrm)
            except Exception as exc:
                rec.meta["error"] = repr(exc)[:200]
            try:
                region = finder(mesh)
                rec.meta["attachment_found"] = region is not None
                rec.metrics = {m: _float(v) for m, v in compute_scalar_metrics(mesh, region).items()}
            except Exception as exc:
                rec.meta["metrics_error"] = repr(exc)[:200]
            rec.quality = mesh_quality(mesh)
            if k < n_meshes:
                rec.mesh = mesh
        out.append(rec)
    return out


