@dataclass
class VAEHandle:
    model: Any
    cfg: Dict[str, Any]
    device: Any
    checkpoint_id: str

    @property
    def coord_scale(self) -> float:
        return float(self.cfg["data"]["coord_scale"])

    @property
    def n_points(self) -> int:
        return int(self.cfg["data"]["n_points"])


def load_vae(run_dir: Path, checkpoint: str = "latest") -> VAEHandle:
    import torch

    from .experiment.checkpoint import CheckpointManager
    from .experiment.run import open_run
    from .experiment.training import get_device
    from .models.spine_vae.model import SpineVAE, SpineVAEConfig

    run = open_run(run_dir)
    cfg = run.load_config()
    model = SpineVAE(SpineVAEConfig.from_mapping(json.loads((run.root / "model_config.json").read_text(encoding="utf-8"))))
    payload = CheckpointManager(run.checkpoints).load(checkpoint, restore_rng=False)
    model.load_state_dict(payload["state"]["ema"]["model"] if "ema" in payload["state"] else payload["state"]["model"])
    device = get_device(cfg.get("device", "auto"))
    model.to(device).eval()
    torch.set_grad_enabled(False)
    return VAEHandle(model, cfg, device, f"{run.experiment_id}:{checkpoint}:step{payload['step']}")


def encode(vae: VAEHandle, points_nm: np.ndarray, normals: Optional[np.ndarray]) -> np.ndarray:
    """Posterior mean of one surface point cloud (nm)."""
    import torch

    p = torch.as_tensor(np.asarray(points_nm, dtype=np.float32) * vae.coord_scale)[None].to(vae.device)
    n = None if normals is None else torch.as_tensor(np.asarray(normals, dtype=np.float32))[None].to(vae.device)
    _, mu, _ = vae.model.encode(p, n, sample=False)
    return mu[0].detach().cpu().numpy()


def surface_cloud(mesh: Any, n: int, seed: int) -> Tuple[np.ndarray, np.ndarray]:
    """Area-weighted surface sample with face normals (the encoder input for a generated mesh)."""
    import trimesh

    pts, face = trimesh.sample.sample_surface(mesh, n, seed=seed)
    return np.asarray(pts, dtype=np.float32), np.asarray(mesh.face_normals[face], dtype=np.float32)


