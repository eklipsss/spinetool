"""Data of the spine-generator atlas (``scripts/neuron_model/build_spine_atlas.py``): one common map of real and
generated spines, their morphometrics and surface quality, and latent traversals of the VAE.

Common space. Every spine - real or generated by ANY model - is encoded by the trained VAE encoder (posterior mean of
its surface point cloud, the same input the encoder was trained on: ``data.n_points`` points with normals, scaled by
``data.coord_scale``). MoGen has no encoder of its own, so this is the only space shared by all generators. The 2-D
map is a UMAP (or PCA) fitted on the REAL reference only; generated spines are projected into it (``transform``), so the
real map does not move when a model is added. A second map uses the standardised morphometrics (PCA fitted on real).

Comparison numbers (generated set vs the real reference):
- per morphometric: W1 / std(real), KS statistic, medians;
- correlation structure: max and mean |R_gen - R_real| over metric pairs;
- latent space: coverage (share of real spines that are the nearest real neighbour of some generated spine), 1-NNA
  (leave-one-out 1-NN accuracy of real vs generated; 0.5 = indistinguishable, 1 = separable) and a memorisation ratio
  (median distance generated -> nearest TRAIN spine divided by the same for real test spines; << 1 = copies).
Surface quality of every mesh: closed, one component, genus, area, roughness (mean dihedral angle between adjacent
faces) and the share of needle-like triangles. Units: nm (the page converts to um for display, explicitly).
"""

