def fit_map(real: np.ndarray, others: Sequence[np.ndarray], *, method: str = "umap", seed: int = 0) -> Tuple[np.ndarray, List[np.ndarray], str]:
    """2-D coordinates of the real points and of every other set, fitted on real only. UMAP needs >= 30 points."""
    if method == "umap" and len(real) >= 30:
        import umap

        reducer = umap.UMAP(n_neighbors=min(30, len(real) - 1), min_dist=0.15, random_state=seed)
        r = reducer.fit_transform(real)
        return r, [reducer.transform(o) if len(o) else np.zeros((0, 2)) for o in others], "UMAP"
    from sklearn.decomposition import PCA

    pca = PCA(n_components=2, random_state=seed).fit(real)
    return pca.transform(real), [pca.transform(o) if len(o) else np.zeros((0, 2)) for o in others], "PCA"


def morph_matrix(records: Sequence[SpineRecord], ref_stats: Optional[Tuple[np.ndarray, np.ndarray, np.ndarray]] = None):
    """Standardised morphometric vectors (log for the 'log' metrics, NaN -> real median). Returns (X, stats)."""
    cols = list(METRIC_INFO)
    raw = np.array([[r.metrics.get(m) if r.metrics.get(m) is not None else np.nan for m in cols] for r in records], dtype=float)
    for j, m in enumerate(cols):
        if METRIC_INFO[m]["log"]:
            raw[:, j] = np.log(np.where(raw[:, j] > 0, raw[:, j], np.nan))
    if ref_stats is None:
        med = np.nanmedian(raw, axis=0)
        mean = np.nanmean(raw, axis=0)
        std = np.nanstd(raw, axis=0)
        ref_stats = (np.nan_to_num(med), np.nan_to_num(mean), np.where(np.nan_to_num(std) > 0, np.nan_to_num(std), 1.0))
    med, mean, std = ref_stats
    filled = np.where(np.isnan(raw), med, raw)
    return (filled - mean) / std, ref_stats


def compare_metric(gen: np.ndarray, real: np.ndarray) -> Dict[str, Optional[float]]:
    from scipy import stats

    g, r = gen[np.isfinite(gen)], real[np.isfinite(real)]
    if len(g) < 3 or len(r) < 3:
        return {"w1_rel": None, "ks": None, "median_gen": None, "median_real": None, "n_gen": int(len(g))}
    return {"w1_rel": float(stats.wasserstein_distance(g, r) / max(np.std(r), 1e-12)), "ks": float(stats.ks_2samp(g, r).statistic),
            "median_gen": float(np.median(g)), "median_real": float(np.median(r)), "n_gen": int(len(g))}


def correlation_gap(gen: np.ndarray, real: np.ndarray) -> Dict[str, Any]:
    """|R_gen - R_real| (Spearman) over the metric columns."""
    from scipy import stats

    def corr(x):
        ok = ~np.isnan(x).any(axis=1)
        return stats.spearmanr(x[ok]).correlation if ok.sum() > 5 else np.full((x.shape[1], x.shape[1]), np.nan)

    rg, rr = corr(gen), corr(real)
    d = np.abs(rg - rr)
    iu = np.triu_indices_from(d, 1)
    return {"real": np.nan_to_num(rr).tolist(), "gen": np.nan_to_num(rg).tolist(),
            "max_gap": float(np.nanmax(d[iu])) if np.isfinite(d[iu]).any() else None, "mean_gap": float(np.nanmean(d[iu])) if np.isfinite(d[iu]).any() else None}


def latent_scores(gen: np.ndarray, real: np.ndarray, train: Optional[np.ndarray]) -> Dict[str, Optional[float]]:
    from scipy.spatial import cKDTree

    out: Dict[str, Optional[float]] = {"coverage": None, "one_nna": None, "memorization_ratio": None}
    if len(gen) < 2 or len(real) < 2:
        return out
    # coverage: real spines that are the nearest real neighbour of at least one generated spine
    _, idx = cKDTree(real).query(gen)
    out["coverage"] = float(len(set(idx.tolist())) / len(real))
    # 1-NNA on a balanced subsample
    n = min(len(gen), len(real))
    rng = np.random.default_rng(0)
    a, b = gen[rng.permutation(len(gen))[:n]], real[rng.permutation(len(real))[:n]]
    x = np.vstack([a, b])
    y = np.r_[np.zeros(n), np.ones(n)]
    _, nn = cKDTree(x).query(x, k=2)
    out["one_nna"] = float((y[nn[:, 1]] == y).mean())
    if train is not None and len(train) >= 2:
        tree = cKDTree(train)
        dg, _ = tree.query(gen)
        dr, _ = tree.query(real)
        out["memorization_ratio"] = float(np.median(dg) / max(np.median(dr), 1e-12))
    return out


