# surface quality
# ---------------------------------------------------------------------------


def mesh_quality(mesh: Any) -> Dict[str, Any]:
    """Closed / components / genus / area / roughness / needles of one trimesh (None -> empty report)."""
    if mesh is None or len(getattr(mesh, "faces", [])) == 0:
        return {"mesh_present": False}
    import trimesh

    out: Dict[str, Any] = {"mesh_present": True, "n_faces": int(len(mesh.faces)), "watertight": bool(mesh.is_watertight)}
    try:
        out["n_components"] = int(len(trimesh.graph.connected_components(mesh.face_adjacency, nodes=np.arange(len(mesh.faces)))))
    except Exception:
        out["n_components"] = None
    out["genus"] = int(round(1 - mesh.euler_number / 2)) if out["watertight"] and out.get("n_components") == 1 else None
    out["area_um2"] = float(mesh.area) * 1e-6
    angles = mesh.face_adjacency_angles
    out["roughness_deg"] = float(np.degrees(angles.mean())) if len(angles) else None
    e = mesh.vertices[mesh.faces]
    lengths = np.linalg.norm(e[:, [1, 2, 0]] - e, axis=2)
    ratio = lengths.max(1) / np.maximum(lengths.min(1), 1e-12)
    out["needle_share"] = float((ratio > 10.0).mean())
    return out


