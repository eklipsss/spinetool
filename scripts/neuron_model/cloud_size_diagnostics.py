"""Point-cloud size before Poisson: generated sets against real clouds of the same test spines (``evaluation/cloud_size.py``).

    python scripts/neuron_model/cloud_size_diagnostics.py --manifest cache/minnie65_v1_60k/manifest.parquet \
        --real real=<real controls>/poisson/seed_1 \
        --gen A=<A>/meshes_poisson_d8_pw8_n500/seed_1 --gen v3=<v3>/meshes_poisson_d8_pw8/seed_1 \
        --gen A-step1000=<curves run>/meshes/step1000 ... --out runs/analysis/neuron-model/<date>_cloud-size

``--gen`` folders: ``sample_*/generated_pointcloud.ply`` (+ ``generated_mesh_postprocessed.off`` if reconstructed);
``--real``: a ``make_real_controls.py`` poisson set (the spine key -> its preprocessing cloud via ``--manifest``).
Writes ``per_sample_<label>.csv``, ``summary.csv`` and ``summary.md`` (median / real median with a 95 % interval;
the real side resampled by neuron).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from src.neuron_model.spine_generation.data.index import load_spine_index  # noqa: E402
from src.neuron_model.spine_generation.evaluation.cloud_size import measure_generated_dir, measure_real_controls, summarise  # noqa: E402


def labelled(values, ap):
    out = {}
    for v in values:
        label, sep, path = v.partition("=")
        if not sep:
            ap.error(f"expected label=path, got {v!r}")
        out[label] = Path(path)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", type=Path, required=True)
    ap.add_argument("--path-mode", default="relative")
    ap.add_argument("--real", required=True, help="label=<real controls poisson set>")
    ap.add_argument("--gen", action="append", default=[], help="label=<folder with sample_*> (repeatable)")
    ap.add_argument("--limit", type=int, help="first N samples per set (smoke tests)")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    real_label, real_dir = next(iter(labelled([args.real], ap).items()))
    index = load_spine_index([args.manifest], path_mode=args.path_mode, check_files=())
    cloud_of = dict(zip(index.frame["spine_key"], index.frame["pointcloud_8192_path"].astype(str)))
    args.out.mkdir(parents=True, exist_ok=True)
    tables = {}
    t = measure_real_controls(real_dir, cloud_of, limit=args.limit)
    print(f"{real_label}: {len(t)} real clouds ({t['spine_key'].str.split('/').str[1].nunique() if len(t) else 0} neurons)", flush=True)
    tables[real_label] = t
    for label, d in labelled(args.gen, ap).items():
        if not d.exists():
            print(f"{label}: {d} does not exist, skipped", flush=True)
            continue
        tables[label] = measure_generated_dir(d, limit=args.limit)
        print(f"{label}: {len(tables[label])} clouds", flush=True)
    for label, t in tables.items():
        t.to_csv(args.out / f"per_sample_{label}.csv", index=False)
    summary = summarise(tables, real_label)
    summary.to_csv(args.out / "summary.csv", index=False)
    lines = ["# Point-cloud size before Poisson", "", f"Reference: {real_label} (real clouds of the same test spines; real median, "
             "interval: real resampled by neuron, generated by sample).", ""]
    for m, g in summary.groupby("measure", sort=False):
        lines += [f"## {m}", "", "| set | n | median | p99 | median / real [95 %] | p99 / real p99 |", "| --- | --- | --- | --- | --- | --- |"]
        for _, r in g.iterrows():
            lines.append(f"| {r.set} | {r.n} | {r['median']:.4g} | {r.p99:.4g} | {r.ratio_to_ref:.3f} [{r.ratio_lo:.3f}; {r.ratio_hi:.3f}] | {r.p99_ratio_to_ref:.2f} |")
        lines.append("")
    (args.out / "summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"-> {args.out}")


if __name__ == "__main__":
    main()
