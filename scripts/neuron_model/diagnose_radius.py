"""Which scale of the radius variation does T0 lose? Semivariogram of log r along the branch, real train branches vs
branches generated by a T0 run for the same conditions / lengths / steps (variogram.py).

Windows (CPU, a minute; the same data arguments as fit_t0.py):

    python scripts/neuron_model/diagnose_radius.py --t0-run runs/training/neuron-model/<id>_t0 \
        data.branches_root=C:/Users/Student/LipsEkaterina/data/minnie65/preprocessed_branches data.splits=<...>/splits_tmp.parquet

Prints, per radius class, sqrt(2 gamma(h)) = the typical relative change of the radius over a lag h (real | generated)
and the ratio generated / real: a ratio << 1 at short lags = a missing fast component, at long lags = a missing slow one.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))
if sys.platform == "win32":
    os.environ.setdefault("KMP_DUPLICATE_LIB_OK", "TRUE")

import torch  # noqa: F401,E402  (first: see fit_t0.py)

import numpy as np  # noqa: E402

from src.neuron_model.branch_data import _cond, branch_key, prepare_training_data, select, t0_training_branches  # noqa: E402
from src.neuron_model.spine_generation.experiment.config import load_config, resolve_path  # noqa: E402
from src.neuron_model.trunk_generation.conditions import DesignEncoder  # noqa: E402
from src.neuron_model.trunk_generation.models.t0_statistical import T0Model  # noqa: E402
from src.neuron_model.trunk_generation.variogram import LAGS_NM, by_radius_class  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", type=Path, default=REPO_ROOT / "configs/neuron-model/trunk/t0.yaml")
    parser.add_argument("--t0-run", type=Path, required=True)
    parser.add_argument("--t0-model", default=None, help="parabola / gam (default: the one chosen in report.json)")
    parser.add_argument("--split", default="train", choices=["train", "val"])
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("overrides", nargs="*")
    args = parser.parse_args()
    cfg = load_config(args.config, args.overrides)
    d = cfg["data"]
    table, _, pack = prepare_training_data(resolve_path(d["branches_root"]), resolve_path(d["pack_dir"]), splits=resolve_path(d["splits"]) if d.get("splits") else None,
                                           io_threads=int(d["io_threads"]))
    sel = select(table, eligible="train_eligible_T", splits=d[f"{args.split}_splits"], exclude_compartments=d.get("exclude_compartments"))
    sel = sel[[branch_key(r) in pack for r in sel.to_dict("records")]].reset_index(drop=True)
    run = args.t0_run if args.t0_run.is_absolute() else REPO_ROOT / args.t0_run
    name = args.t0_model or json.loads((run / "report.json").read_text(encoding="utf-8"))["chosen"]
    model = T0Model.load(run / f"t0_{name}.json")
    branches = t0_training_branches(sel, pack, model.encoder)
    requests = [dict(_cond(r), length_nm=b.length, step_nm=b.step) for r, b in zip(sel.to_dict("records"), branches)]
    gen = model.sample(requests, np.random.default_rng(args.seed))
    radii = [float(np.median(np.exp(b.log_radius))) for b in branches]
    real = by_radius_class([b.log_radius for b in branches], [b.step for b in branches], radii)
    fake = by_radius_class([g["log_radius"] for g in gen], [g["step"] for g in gen], radii)  # classes by the REAL median radius of the request
    print(f"[radius] T0 {run.name}/{name}, {len(branches)} {args.split} branches; sqrt(2 gamma(h)) = typical relative radius change over the lag h")
    for cls in real:
        print(f"\n{cls} (n = {real[cls]['n']})")
        print("  lag, um      real   generated   generated/real")
        for h in LAGS_NM:
            r, g = real[cls].get(h), fake.get(cls, {}).get(h)
            if r is None or g is None:
                continue
            print(f"  {h / 1000.0:6.2f}   {np.sqrt(2 * r):7.3f}   {np.sqrt(2 * g):7.3f}   {np.sqrt(g / r):7.2f}")


if __name__ == "__main__":
    main()
